/**
 * Returns matrix row objects for all 10 countries for the selected indicator & year.
 */
export function getMacroMatrixData(indicator: string, year: number) {
  const currentYear = new Date().getFullYear();
  const currentMonth = new Date().getMonth() + 1;
  const endMonth = year === currentYear ? currentMonth : 12;
  const months = Array.from({ length: endMonth }).map((_, i) => `${year}-${(i + 1).toString().padStart(2, '0')}`);

  const indData = MASTER_MACRO_DATABASE[indicator] || {};

  return COUNTRIES.map((c, i) => {
    const countryMonths = indData[c.country] || {};
    return {
      ...c,
      data: months.map((m, j) => {
        const raw = countryMonths[m];
        if (raw === undefined || raw === null) {
          // Check if it is a missing print
          return {
            value: null,
            status: "missing" as const
          };
        }

        // Formatting based on indicator
        let formattedVal: string = "";
        if (indicator === "FX Reserves") {
          formattedVal = Math.round(Number(raw)).toLocaleString();
        } else if (indicator === "Interest Rate") {
          formattedVal = Number(raw).toFixed(2);
        } else {
          formattedVal = Number(raw).toFixed(1);
        }

        return {
          value: formattedVal,
          status: "published" as const
        };
      })
    };
  });
}

/**
 * Returns differential transformation for a given pair, indicator, and year.
 */
export function getCombinedDifferentialData(pairName: string, indicator: string, year: number) {
  const pair = PAIRS.find(p => p.name === pairName) || PAIRS[0];
  const currentYear = new Date().getFullYear();
  const currentMonth = new Date().getMonth() + 1;
  const endMonth = year === currentYear ? currentMonth : 12;
  const months = Array.from({ length: endMonth }).map((_, i) => `${year}-${(i + 1).toString().padStart(2, '0')}`);

  const indData = MASTER_MACRO_DATABASE[indicator] || {};
  const baseMap = indData[pair.baseCountry] || {};
  const quoteMap = indData[pair.quoteCountry] || {};

  return months.map(m => {
    const rawBase = baseMap[m] !== undefined && baseMap[m] !== null ? Number(baseMap[m]) : 0.0;
    const rawQuote = quoteMap[m] !== undefined && quoteMap[m] !== null ? Number(quoteMap[m]) : 0.0;

    let baseVal = "";
    let quoteVal = "";
    let diffNum = 0;
    let diff = "";
    let rating = 0;
    let rule = "-1.0 to 1.0";
    let regime = "Neutral / Balanced";

    if (indicator === "FX Reserves") {
      const getRollingAvg = (countryMap: Record<string, number | null>, curMonth: string) => {
        const [yr, mo] = curMonth.split('-').map(Number);
        const deltas: number[] = [];
        for (let k = 0; k < 12; k++) {
          let targetM = mo - k;
          let targetY = yr;
          while (targetM <= 0) {
            targetM += 12;
            targetY -= 1;
          }
          const curKey = `${targetY}-${targetM.toString().padStart(2, '0')}`;
          let prevM = targetM - 1;
          let prevY = targetY;
          if (prevM <= 0) {
            prevM = 12;
            prevY -= 1;
          }
          const prevKey = `${prevY}-${prevM.toString().padStart(2, '0')}`;
          const curVal = countryMap[curKey];
          const prevVal = countryMap[prevKey];
          if (curVal !== undefined && curVal !== null && prevVal !== undefined && prevVal !== null) {
            deltas.push(Number(curVal) - Number(prevVal));
          }
        }
        if (deltas.length === 0) return 0;
        return deltas.reduce((a, b) => a + b, 0) / deltas.length;
      };

      const baseFlow = getRollingAvg(baseMap, m);
      const quoteFlow = getRollingAvg(quoteMap, m);
      diffNum = parseFloat((baseFlow - quoteFlow).toFixed(1));
      baseVal = (baseFlow >= 0 ? "+" : "") + Math.round(baseFlow).toLocaleString();
      quoteVal = (quoteFlow >= 0 ? "+" : "") + Math.round(quoteFlow).toLocaleString();
      diff = (diffNum >= 0 ? "+" : "") + Math.round(diffNum).toLocaleString();

      if (diffNum >= 600) {
        rating = 10;
        rule = "+600M to +∞";
        regime = "Strong Bullish Bias";
      } else if (diffNum >= 200) {
        rating = 5;
        rule = "+200M to +600M";
        regime = "Moderate Bullish Bias";
      } else if (diffNum <= -600) {
        rating = -10;
        rule = "-∞ to -600M";
        regime = "Strong Bearish Bias";
      } else if (diffNum <= -200) {
        rating = -5;
        rule = "-600M to -200M";
        regime = "Moderate Bearish Bias";
      } else {
        rating = 0;
        rule = "-200M to +200M";
        regime = "Neutral / Balanced";
      }
    } else if (indicator === "CPI") {
      baseVal = rawBase.toFixed(1);
      quoteVal = rawQuote.toFixed(1);
      diffNum = parseFloat((rawBase - rawQuote).toFixed(1));
      diff = (diffNum > 0 ? "+" : "") + diffNum.toFixed(1);

      if (diffNum <= -2.0) {
        rating = 10;
        rule = "-∞ to -2.0%";
        regime = "Strong Bullish Bias";
      } else if (diffNum <= -1.0) {
        rating = 5;
        rule = "-2.0% to -1.0%";
        regime = "Moderate Bullish Bias";
      } else if (diffNum >= 2.0) {
        rating = -10;
        rule = "+2.0% to +∞";
        regime = "Strong Bearish Bias";
      } else if (diffNum >= 1.0) {
        rating = -5;
        rule = "+1.0% to +2.0%";
        regime = "Moderate Bearish Bias";
      } else {
        rating = 0;
        rule = "-1.0% to +1.0%";
        regime = "Neutral / Balanced";
      }
    } else if (indicator === "Interest Rate") {
      baseVal = rawBase.toFixed(2);
      quoteVal = rawQuote.toFixed(2);
      diffNum = parseFloat((rawBase - rawQuote).toFixed(2));
      diff = (diffNum > 0 ? "+" : "") + diffNum.toFixed(2);

      if (diffNum >= 2.0) {
        rating = 10;
        rule = "2.0% to +∞";
        regime = "Strong Bullish Bias";
      } else if (diffNum >= 1.0) {
        rating = 5;
        rule = "1.0% to 2.0%";
        regime = "Moderate Bullish Bias";
      } else if (diffNum <= -2.0) {
        rating = -10;
        rule = "-∞ to -2.0%";
        regime = "Strong Bearish Bias";
      } else if (diffNum <= -1.0) {
        rating = -5;
        rule = "-2.0% to -1.0%";
        regime = "Moderate Bearish Bias";
      } else {
        rating = 0;
        rule = "-1.0% to 1.0%";
        regime = "Neutral / Balanced";
      }
    } else {
      // GDP, Current Account, Equity
      baseVal = rawBase.toFixed(1);
      quoteVal = rawQuote.toFixed(1);
      diffNum = parseFloat((rawBase - rawQuote).toFixed(1));
      diff = (diffNum > 0 ? "+" : "") + diffNum.toFixed(1);

      if (diffNum >= 2.0) {
        rating = 10;
        rule = "2.0 to +∞";
        regime = "Strong Bullish Bias";
      } else if (diffNum >= 1.0) {
        rating = 5;
        rule = "1.0 to 2.0";
        regime = "Moderate Bullish Bias";
      } else if (diffNum <= -2.0) {
        rating = -10;
        rule = "-∞ to -2.0";
        regime = "Strong Bearish Bias";
      } else if (diffNum <= -1.0) {
        rating = -5;
        rule = "-2.0 to -1.0";
        regime = "Moderate Bearish Bias";
      } else {
        rating = 0;
        rule = "-1.0 to 1.0";
        regime = "Neutral / Balanced";
      }
    }

    return {
      month: m,
      baseVal,
      quoteVal,
      diff,
      diffNum,
      rating,
      rule,
      regime
    };
  });
}
